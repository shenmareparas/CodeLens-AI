namespace CodeLens.Infrastructure.AI;

using CodeLens.Core.Entities;
using System.Globalization;
using System.Text;

/// <summary>
/// Compiles the standardized PROJECT_KNOWLEDGE.md dossier from deterministic telemetry
/// and Gemini 3.8 Flash synthesis outputs.
/// </summary>
public static class MarkdownDossierBuilder
{
    public static string BuildDossierMarkdown(
        string owner,
        string repo,
        TelemetryData telemetry,
        AiInsights insights,
        string defaultBranch = "main",
        DateTimeOffset? timestamp = null)
    {
        var ts = (timestamp ?? DateTimeOffset.UtcNow).ToString("yyyy-MM-dd HH:mm:ss UTC", CultureInfo.InvariantCulture);
        var safeOwner = string.IsNullOrWhiteSpace(owner) ? "Unknown" : owner.Trim();
        var safeRepo = string.IsNullOrWhiteSpace(repo) ? "Repository" : repo.Trim();

        var sb = new StringBuilder();

        // Title and Metadata
        sb.AppendLine($"# Project Knowledge Dossier: {safeOwner}/{safeRepo}");
        sb.AppendLine($"> Generated by CodeLens AI | Model: Gemini 3.8 Flash | Date: {ts}");
        sb.AppendLine();

        // 1. Executive Architecture Overview
        sb.AppendLine("## 1. Executive Architecture Overview");
        sb.AppendLine(string.IsNullOrWhiteSpace(insights.Eli5Summary)
            ? $"*{safeRepo} is a software project analyzed by CodeLens AI.*"
            : insights.Eli5Summary.Trim());
        sb.AppendLine();

        // 2. Repository Health
        sb.AppendLine("## 2. Repository Health");
        sb.AppendLine($"- **Default Branch:** `{defaultBranch}`");
        sb.AppendLine($"- **Stars / Forks:** ⭐ {telemetry.Stars:N0} | 🍴 {telemetry.Forks:N0}");
        sb.AppendLine($"- **Release Cadence:** {telemetry.ReleaseStatus} (Last release: {telemetry.DaysSinceLastRelease} days ago)");
        
        var sparklineArray = telemetry.WeeklyCommitsSparkline.Count > 0
            ? $"[{string.Join(", ", telemetry.WeeklyCommitsSparkline)}]"
            : "[]";
        sb.AppendLine($"- **8-Week Commit Trend:** `{sparklineArray}`");

        var licenseName = string.IsNullOrWhiteSpace(telemetry.License) ? "None Specified" : telemetry.License;
        var licenseVerdict = string.IsNullOrWhiteSpace(insights.LicenseVerdict) ? "Permissive commercial use under review." : insights.LicenseVerdict.Trim();
        sb.AppendLine($"- **License & Commercial Verdict:** {licenseName} — {licenseVerdict}");

        var languagesList = telemetry.Languages.Count > 0
            ? string.Join(", ", telemetry.Languages.OrderByDescending(kv => kv.Value).Select(kv => $"{kv.Key} ({kv.Value:F1}%)"))
            : "Unknown";
        sb.AppendLine($"- **Language Distribution:** {languagesList}");
        sb.AppendLine();

        // 3. System Architecture Diagram
        sb.AppendLine("## 3. System Architecture Diagram");
        sb.AppendLine("```mermaid");
        var sanitizedMermaid = MermaidSanitizer.Sanitize(insights.MermaidDiagram, safeRepo);
        sb.AppendLine(sanitizedMermaid);
        sb.AppendLine("```");
        sb.AppendLine();

        // 4. Complexity Heatmap (Top Bug Hotspots)
        sb.AppendLine("## 4. Complexity Heatmap (Top Bug Hotspots)");
        sb.AppendLine("| File Path | Cyclomatic Complexity | Recent Commit Churn | Hotspot Risk Score |");
        sb.AppendLine("| :--- | :--- | :--- | :--- |");
        if (telemetry.Hotspots.Count > 0)
        {
            foreach (var hotspot in telemetry.Hotspots.OrderByDescending(h => h.Score).Take(15))
            {
                sb.AppendLine($"| `{hotspot.File}` | {hotspot.Complexity} | {hotspot.Churn} | {hotspot.Score:F2} |");
            }
        }
        else
        {
            sb.AppendLine("| *No high-risk hotspots detected* | 0 | 0 | 0.00 |");
        }
        sb.AppendLine();

        // 5. Dependency & Ecosystem Inventory
        sb.AppendLine("## 5. Dependency & Ecosystem Inventory");
        sb.AppendLine("| Ecosystem | Package / Library | Version / Target |");
        sb.AppendLine("| :--- | :--- | :--- |");
        if (telemetry.Dependencies.Count > 0)
        {
            foreach (var dep in telemetry.Dependencies.OrderBy(d => d.Ecosystem).ThenBy(d => d.Package).Take(30))
            {
                sb.AppendLine($"| {dep.Ecosystem} | `{dep.Package}` | {dep.Version} |");
            }
        }
        else
        {
            sb.AppendLine("| None | *No external package dependencies detected* | - |");
        }
        sb.AppendLine();

        // 6. Dead Code & Unreferenced Candidates
        sb.AppendLine("## 6. Dead Code & Unreferenced Candidates");
        if (telemetry.DeadCode.Count > 0)
        {
            foreach (var dead in telemetry.DeadCode.Take(15))
            {
                sb.AppendLine($"- `{dead}`");
            }
        }
        else
        {
            sb.AppendLine("- *No dead or unreferenced code candidates detected.*");
        }
        sb.AppendLine();

        // 7. Security & Secret Exposure Surface
        sb.AppendLine("## 7. Security & Secret Exposure Surface");
        if (telemetry.SecretAlerts.Count > 0)
        {
            foreach (var alert in telemetry.SecretAlerts)
            {
                sb.AppendLine($"- ⚠️ {alert}");
            }
        }
        else
        {
            sb.AppendLine("- ✅ *No credentials, private keys, or exposed secrets detected.*");
        }
        sb.AppendLine();

        // 8. Architectural Anti-Patterns & Code Smells
        sb.AppendLine("## 8. Architectural Anti-Patterns & Code Smells");
        sb.AppendLine(string.IsNullOrWhiteSpace(insights.CodeSmells)
            ? "*No critical anti-patterns or architectural circularities flagged.*"
            : insights.CodeSmells.Trim());
        sb.AppendLine();

        // 9. Developer Onboarding & First-Day Runbook
        sb.AppendLine("## 9. Developer Onboarding & First-Day Runbook");
        sb.AppendLine(string.IsNullOrWhiteSpace(insights.OnboardingRunbook)
            ? "*Clone the repository, inspect the dependencies listed above, and run the standard build/test suite for this ecosystem.*"
            : insights.OnboardingRunbook.Trim());

        return sb.ToString();
    }
}
